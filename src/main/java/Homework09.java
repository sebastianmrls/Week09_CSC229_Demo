import java.util.ArrayList;

public class Homework09 {

    public static void main(String[] args) {
        int triangle = 0;
        int n = 1;
        ArrayList<Integer> divisors = new ArrayList<>();

        while (divisors.size() <= 100) {
            triangle = triangle + n;
            divisors.clear();

            for (int d = 1; d <= triangle; d++) {
                if (triangle % d == 0) {
                    divisors.add(d);
                }
            }

            n++;
        }

        System.out.println("First triangle number with more than 100 divisors: " + triangle);
        System.out.println("Number of divisors: " + divisors.size());
    }

    /*
     * Original author: MoaathAlrajab.
     *
     * Homework 09:
     * The sequence of triangle numbers is generated by adding the natural
     * numbers. The 7th triangle number is 1 + 2 + 3 + 4 + 5 + 6 + 7 = 28.
     * The first ten terms are:
     * 1, 3, 6, 10, 15, 21, 28, 36, 45, 55, ...
     *
     * Factors of the first seven triangle numbers:
     *  1: 1
     *  3: 1, 3
     *  6: 1, 2, 3, 6
     * 10: 1, 2, 5, 10
     * 15: 1, 3, 5, 15
     * 21: 1, 3, 7, 21
     * 28: 1, 2, 4, 7, 14, 28
     *
     * 28 is the first triangle number to have over five divisors.
     * What is the first triangle number to have over one hundred divisors?
     *
     * Algorithm:
     * 1. Generate triangle numbers in order by adding the next natural number.
     * 2. Try every number from 1 to the triangle number.
     *    Add it to the list when the remainder is zero.
     *    Clear the list before checking each new triangle number.
     * 3. Stop when the list contains more than 100 divisors.
     *
     * Result: 73920, the 384th triangle number, has 112 divisors.
     */
}
